// Checks for what you say on the job. Run: npx tsx e2e/voice.ts
import { parseItems, parseUtterance, spokenLength, sayLength } from '../src/voice.ts';

let fails = 0;
const ok = (c: boolean, m: string, got?: unknown) => {
  console.log(c ? '✓' : '✗', m, c ? '' : JSON.stringify(got));
  if (!c) fails++;
};
const L = (s: string, v: number | null) => ok(spokenLength(s) === v, `length "${s}" = ${v}`, spokenLength(s));
L('12 foot 6', 150);
L('twelve foot six', 150);
L('12 feet 6 inches', 150);
L("12' 6\"", 150);
L('12 ft 6 in', 150);
L('12 6', 150);
L('12 foot 6 and a half', 150.5);
L('twelve and a half feet', 150);
L('150 inches', 150);
L('eleven foot three and three quarters', 135.75);
L('10 foot even', 120);
L('9 foot 5 and 5 eighths', 113.625);
L('one hundred and forty four inches', 144);
L('thirty two inches', 32);
L('it\'s about 14 feet', 168);
L('kitchen', null);
const C = (s: string, tab: 'plan' | 'list' = 'plan') => parseUtterance(s, { rooms: ['Kitchen', 'Bedroom', 'Room 2', 'Hall bath'], tab });
const kinds = (s: string, tab: 'plan' | 'list' = 'plan') => C(s, tab).map((c) => c.k).join(',');
ok(kinds('12 foot 6 next 10 foot 2 next') === 'length,next,length,next', 'chain of walls', C('12 foot 6 next 10 foot 2 next'));
ok(kinds('12 feet, 6 inches') === 'length', 'comma inside a length', C('12 feet, 6 inches'));
const k = C('kitchen north wall 14 foot 2')[0];
ok(k.k === 'length' && k.room === 'Kitchen' && k.wall?.side === 'top' && k.inches === 170, 'room + side + length', k);
const w3 = C('bedroom wall 3 11 foot')[0];
ok(w3.k === 'length' && w3.room === 'Bedroom' && w3.wall?.index === 2 && w3.inches === 132, 'room + wall number', w3);
const fx = C('no, 12 foot')[0];
ok(fx.k === 'fix' && fx.inches === 144, 'correction', fx);
const fx2 = C('I meant 11 4')[0];
ok(fx2.k === 'fix' && fx2.inches === 136, 'I meant', fx2);
const d = C('32 inch door')[0];
ok(d.k === 'opening' && d.type === 'door' && d.widthIn === 32, 'door size', d);
const d3 = C('3 foot door')[0];
ok(d3.k === 'opening' && d3.widthIn === 36, 'door in feet', d3);
const win = C('window 36 by 48')[0];
ok(win.k === 'opening' && win.type === 'window' && win.widthIn === 36 && win.heightIn === 48, 'window size', win);
const nd = C('add a new door')[0];
ok(nd.k === 'opening' && nd.newDoor === true, 'add a new door is a door, not a list item', nd);
ok(kinds('no base') === 'nobase', 'no base', C('no base'));
ok(kinds('cabinets here') === 'nobase', 'cabinets', C('cabinets here'));
ok(kinds('undo') === 'undo' && kinds('scratch that') === 'undo', 'undo words');
ok(kinds('read it back') === 'status', 'status');
ok(kinds('shoe molding') === 'scope' && kinds('quarter round') === 'scope', 'shoe', C('quarter round'));
ok(kinds('LVP') === 'scope', 'lvp');
const nr = C('new room laundry 8 by 6')[0];
ok(nr.k === 'newroom' && nr.name === 'Laundry' && nr.L === 96 && nr.W === 72, 'new room with size', nr);
const a = C('add two tubes of caulk and a box of shims')[0];
ok(a.k === 'add' && a.items.length === 2 && a.items[0].qty === 2 && a.items[0].unit === 'tube' && a.items[0].name === 'Caulk' && a.items[1].unit === 'box', 'add two things', a);
const a2 = C("don't forget the 2 inch brads")[0];
ok(a2.k === 'add' && a2.items[0].name === '2" brads' && a2.items[0].qty === 1, 'number in a name stays', a2);
const a3 = C('we need 3 shims, painter\'s tape and a couple of rags')[0];
ok(a3.k === 'add' && a3.items.length === 3 && a3.items[0].qty === 3 && a3.items[2].qty === 2, 'list of three', a3);
ok(kinds('caulk and wood glue', 'list') === 'add', 'on the list tab anything is an item');
ok(kinds('caulk and wood glue', 'plan') === 'unknown', 'on the plan tab it asks');
const g = C('got the caulk')[0];
ok(g.k === 'got' && g.what === 'caulk', 'got it', g);
const items = parseItems('a gallon of primer, 2 rolls of tape');
ok(items[0].unit === 'gallon' && items[1].qty === 2 && items[1].unit === 'roll', 'units', items);
ok(sayLength(150.5) === '12 foot 6 and a half', 'say it back', sayLength(150.5));
ok(sayLength(144) === '12 foot even', 'say even', sayLength(144));
ok(kinds('skip the base') !== 'next', 'skip the base is not next', C('skip the base'));
console.log(fails ? `${fails} failed` : 'all good');
process.exit(fails ? 1 : 0);
